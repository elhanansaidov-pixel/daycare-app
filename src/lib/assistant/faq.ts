const PREFIX = /^[והבלשמכ]{1,2}(?=[א-ת]{3,})/;
const norm = (s: string) =>
  s
    .replace(/[֑-ׇ]/g, '')
    .replace(/[^א-תa-z0-9\s]/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();

function tokens(s: string): Set<string> {
  const out = new Set<string>();
  for (const w of norm(s).split(' ')) {
    if (!w) continue;
    out.add(w);
    out.add(w.replace(PREFIX, ''));
    if (w.length > 4) out.add(w.slice(1));
  }
  return out;
}

/** Best matching answers for a free-text question (up to 3). */
export function searchFaq(query: string): Faq[] {
  const qn = ` ${norm(query)} `;
  const qt = tokens(query);
  if (!qn.trim()) return [];
  const scored = FAQ.map((f) => {
    let score = 0;
    for (const k of f.keys) {
      const kn = norm(k);
      if (kn.includes(' ')) {
        if (qn.includes(kn)) score += kn.length + 2;
        continue;
      }
      const ks = kn.replace(PREFIX, '');
      for (const t of qt) {
        if (t === kn || t === ks) {
          score += kn.length + 1;
          break;
        }
        if (ks.length >= 3 && t.length >= 3 && (t.startsWith(ks) || ks.startsWith(t))) {
          score += Math.min(ks.length, t.length) - 1;
          break;
        }
      }
    }
    if (qn.includes(norm(f.q).slice(0, 12))) score += 3;
    return { f, score };
  })
    .filter((x) => x.score >= 3)
    .sort((a, b) => b.score - a.score);
  return scored.slice(0, 3).map((x) => x.f);
}

export const faqById = (id: string) => FAQ.find((f) => f.id === id);
